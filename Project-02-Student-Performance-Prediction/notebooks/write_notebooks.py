def cell_code(source_lines, execution_count=None):
    src = [s + "\n" for s in source_lines]
    return {
        "cell_type": "code",
        "execution_count": execution_count,
        "metadata": {},
        "outputs": [],
        "source": src
    }


def cell_md(source_lines):
    src = [s + "\n" for s in source_lines]
    return {
        "cell_type": "markdown",
        "metadata": {},
        "source": src
    }


